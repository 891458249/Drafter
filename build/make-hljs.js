// 把 highlight.js(CJS)打成浏览器可直接加载的单文件 src/vendor/hljs.js。
// highlight.js 的 require 全是字面量相对路径(common → core + languages/*),
// 递归收集后在打包期把每个 require 静态解析成模块 id,包一层微型 module 运行时。
// 用法:node build/make-hljs.js(highlight.js 升级后重跑一次即可)
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..', 'node_modules', 'highlight.js', 'lib');
const OUT = path.join(__dirname, '..', 'src', 'vendor', 'hljs.js');

const modules = new Map(); // id(如 'common.js' / 'languages/bash.js') -> 替换过 require 的源码

function add(id) {
  if (modules.has(id)) return;
  const file = path.join(ROOT, id);
  let code = fs.readFileSync(file, 'utf8');
  // 先收集依赖再替换,避免替换过程影响匹配
  const deps = [];
  code = code.replace(/require\('(\.[^']+)'\)/g, (_m, rel) => {
    let dep = path.posix.join(path.posix.dirname(id), rel);
    if (!dep.endsWith('.js')) dep += '.js';
    deps.push(dep);
    return `__req(${JSON.stringify(dep)})`;
  });
  modules.set(id, code);
  for (const d of deps) add(d);
}

add('common.js');

let out = `// GENERATED by build/make-hljs.js — 请勿手改;highlight.js 升级后执行 node build/make-hljs.js 重新生成
(function () {
  var __mods = {};
  var __cache = {};
  function __req(id) {
    if (__cache[id]) return __cache[id].exports;
    var m = { exports: {} };
    __cache[id] = m;
    __mods[id](m, m.exports, __req);
    return m.exports;
  }
`;
for (const [id, code] of modules) {
  out += `\n__mods[${JSON.stringify(id)}] = function (module, exports, __req) {\n${code}\n};\n`;
}
out += `\nwindow.hljs = __req('common.js');\n})();\n`;

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, out, 'utf8');
console.log(`[make-hljs] ${modules.size} modules -> ${path.relative(process.cwd(), OUT)} (${(out.length / 1024).toFixed(0)} KB)`);
